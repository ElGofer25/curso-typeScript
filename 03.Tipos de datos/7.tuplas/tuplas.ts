//En TypeScript, una tupla se define indicando el tipo de cada posición:

let coordenada: [number, number];

//Y después puedes asignarle valores:

coordenada = [10, 20];

//También directamente:

let coordenada1: [number, number] = [10, 20];

/*Aquí:

posición 0 → number
posición 1 → number

Una tupla tiene orden y cantidad de elementos definidos.*/